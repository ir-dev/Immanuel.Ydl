#!/usr/bin/env python3
"""Regenerate every ARK-RAPID icon and logo the web app ships, from the vector master.

    python3 branding/build.py

Reads branding/ark-rapid.svg and writes into src/Ark.Ydl/wwwroot:

    favicon.ico                      16/32/48, the simplified small-size mark
    img/favicon.svg                  browser tab icon (simplified, no sun rays)
    img/icon.svg                     detailed app tile (also the notification / fallback image)
    img/mark.svg                     <symbol>s the page themes with CSS: #mark, #wordmark, #tagline
    img/logo.svg, img/logo.png       the full lockup (logo.svg follows the OS light/dark setting)
    img/apple-touch-icon.png         180, full bleed (iOS rounds the corners itself)
    img/icon-192.png, icon-512.png   PWA "any"
    img/icon-maskable-*.png          PWA "maskable": emblem kept inside the 80 % safe circle
    img/icon-monochrome.png          PWA "monochrome": white silhouette, alpha only

Needs Pillow (pip install pillow) and Inkscape for SVG -> PNG: $INKSCAPE, else the macOS app, else
`inkscape` on PATH.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
WWW = HERE.parent / "src" / "Ark.Ydl" / "wwwroot"
MASTER = HERE / "ark-rapid.svg"

# Brand palette (sampled from source/lockup.png and source/tile-dark.png).
NAVY, GOLD, TEAL = "#0d2841", "#d0a548", "#1d7b8c"
CREAM, GOLD_ON_NAVY, TEAL_ON_NAVY = "#fcf9f5", "#dcb257", "#2b97a8"
TILE_TOP, TILE_BOTTOM = "#153a60", "#0a1e35"

EMBLEM_BOX = (390, 4, 680, 820)  # x, y, w, h of the emblem in master coordinates
EMBLEM_CX, EMBLEM_CY, EMBLEM_H = 730, 416, 808  # visual centre and height of the drawn emblem

GENERATED = "<!-- Generated by branding/build.py from branding/ark-rapid.svg. Edit the master, not this file. -->"


def parts() -> dict[str, str]:
    svg = MASTER.read_text()
    found = dict(re.findall(r'<path id="(\w+)"[^>]*?\sd="([^"]+)"', svg))
    missing = {"arch", "hull", "waves", "rays", "play", "arrow", "word", "tag"} - found.keys()
    if missing:
        sys.exit(f"{MASTER.name} is missing path ids: {', '.join(sorted(missing))}")
    return found


def bbox(d: str, pad: float = 2) -> tuple[float, float, float, float]:
    """Bounding box of a path from its points (potrace control points hug the curve closely)."""
    nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", d.replace("H", " ").replace("V", " "))]
    xs, ys = nums[0::2], nums[1::2]
    return min(xs) - pad, min(ys) - pad, max(xs) - min(xs) + 2 * pad, max(ys) - min(ys) + 2 * pad


def emblem(p: dict[str, str], ink: str, sun: str, sea: str, *, small: bool = False) -> str:
    """The emblem as plain paths. small=True drops the sun rays, fattens the hull and arch and
    enlarges the play button and arrow a little (about the centre line), because at 16-48 px the rays
    turn to a haze, the hull stripes to noise, and play + arrow merge into one bar."""
    if small:
        bold = f' stroke="{ink}" stroke-width="22" stroke-linejoin="round"'
        k, cx, cy = 1.22, EMBLEM_CX, 442
        grow = f'translate({cx * (1 - k):.1f} {cy * (1 - k):.1f}) scale({k})'
        return (f'<path fill="{ink}"{bold} d="{p["arch"]}"/>'
                f'<path fill="{ink}"{bold} d="{p["hull"]}"/>'
                f'<path fill="{sea}" stroke="{sea}" stroke-width="10" stroke-linejoin="round" d="{p["waves"]}"/>'
                f'<g transform="{grow}">'
                f'<path fill="{sun}" stroke="{sun}" stroke-width="14" stroke-linejoin="round" d="{p["play"]}"/>'
                f'<path fill="{sea}" stroke="{sea}" stroke-width="8" stroke-linejoin="round" d="{p["arrow"]}"/></g>')
    return (f'<path fill="{ink}" d="{p["arch"]}"/>'
            f'<path fill="{ink}" fill-rule="evenodd" d="{p["hull"]}"/>'
            f'<path fill="{sea}" d="{p["waves"]}"/>'
            f'<path fill="{sun}" d="{p["rays"]}"/>'
            f'<path fill="{sun}" d="{p["play"]}"/>'
            f'<path fill="{sea}" d="{p["arrow"]}"/>')


def place(size: float, height_frac: float, dy: float = 0) -> str:
    """transform that centres the emblem in a size x size canvas at height_frac of its height."""
    s = size * height_frac / EMBLEM_H
    return f"translate({size / 2 - EMBLEM_CX * s:.3f} {size / 2 + dy - EMBLEM_CY * s:.3f}) scale({s:.5f})"


def tile(p: dict[str, str], *, size: int = 512, radius: float = 0.22, height_frac: float = 0.66,
         small: bool = False, glow: bool = True) -> str:
    r = size * radius
    glow_el = (f'<circle cx="{size / 2}" cy="{size * 0.43:.1f}" r="{size * 0.36:.1f}" fill="url(#glow)"/>'
               if glow else "")
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">
{GENERATED}
<title>ARK-RAPID</title>
<defs>
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{TILE_TOP}"/><stop offset="1" stop-color="{TILE_BOTTOM}"/></linearGradient>
<radialGradient id="glow"><stop offset="0" stop-color="{GOLD_ON_NAVY}" stop-opacity=".26"/><stop offset="1" stop-color="{GOLD_ON_NAVY}" stop-opacity="0"/></radialGradient>
</defs>
<rect width="{size}" height="{size}" rx="{r:.1f}" fill="url(#bg)"/>
{glow_el}
<g transform="{place(size, height_frac, size * 0.01)}">{emblem(p, CREAM, GOLD_ON_NAVY, TEAL_ON_NAVY, small=small)}</g>
</svg>
'''


def mark_symbols(p: dict[str, str]) -> str:
    """Symbols the page uses via <svg><use href="/img/mark.svg#mark"/></svg>. Colours come from
    CSS custom properties on the <use> (they inherit into its shadow tree), so one file serves the
    light and dark themes: --mark-ink, --mark-sun, --mark-sea, and --mark-rays (opacity, 0 hides
    the rays at small sizes)."""
    ink, sun, sea = f"var(--mark-ink,{NAVY})", f"var(--mark-sun,{GOLD})", f"var(--mark-sea,{TEAL})"
    wx, wy, ww, wh = bbox(p["word"])
    tx, ty, tw, th = bbox(p["tag"])
    ex, ey, ew, eh = EMBLEM_BOX
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{ex} {ey} {ew} {eh}">
{GENERATED}
<symbol id="mark" viewBox="{ex} {ey} {ew} {eh}">
<path style="fill:{ink}" d="{p["arch"]}"/>
<path style="fill:{ink}" fill-rule="evenodd" d="{p["hull"]}"/>
<path style="fill:{sea}" d="{p["waves"]}"/>
<path style="fill:{sun};opacity:var(--mark-rays,1)" d="{p["rays"]}"/>
<path style="fill:{sun}" d="{p["play"]}"/>
<path style="fill:{sea}" d="{p["arrow"]}"/>
</symbol>
<symbol id="wordmark" viewBox="{wx:.0f} {wy:.0f} {ww:.0f} {wh:.0f}">
<path style="fill:var(--mark-word,{NAVY})" fill-rule="evenodd" d="{p["word"]}"/>
</symbol>
<symbol id="tagline" viewBox="{tx:.0f} {ty:.0f} {tw:.0f} {th:.0f}">
<path style="fill:var(--mark-tag,{GOLD})" fill-rule="evenodd" d="{p["tag"]}"/>
</symbol>
<use href="#mark"/>
</svg>
'''


def lockup(p: dict[str, str], *, adaptive: bool) -> str:
    style = ""
    if adaptive:  # follows the viewer's OS setting where it is shown as an <img> (GitHub README, docs)
        style = (f"<style>.i{{fill:{NAVY}}}.s{{fill:{GOLD}}}.t{{fill:{TEAL}}}"
                 f"@media (prefers-color-scheme:dark){{.i{{fill:{CREAM}}}.s{{fill:{GOLD_ON_NAVY}}}.t{{fill:{TEAL_ON_NAVY}}}}}</style>")
    cls = (lambda c: f' class="{c}"') if adaptive else (lambda c: f' fill="{dict(i=NAVY, s=GOLD, t=TEAL)[c]}"')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="110 0 1210 1120" width="1210" height="1120">
{GENERATED}
<title>ARK-RAPID video downloader</title>{style}
<path{cls("i")} d="{p["arch"]}"/><path{cls("i")} fill-rule="evenodd" d="{p["hull"]}"/>
<path{cls("t")} d="{p["waves"]}"/><path{cls("s")} d="{p["rays"]}"/><path{cls("s")} d="{p["play"]}"/>
<path{cls("t")} d="{p["arrow"]}"/>
<path{cls("i")} fill-rule="evenodd" d="{p["word"]}"/><path{cls("s")} fill-rule="evenodd" d="{p["tag"]}"/>
</svg>
'''


def full_bleed(p: dict[str, str], size: int, height_frac: float, *, small: bool = False) -> str:
    return tile(p, size=size, radius=0, height_frac=height_frac, small=small)


def monochrome(p: dict[str, str], size: int = 512) -> str:
    w = "#ffffff"
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">
<g transform="{place(size, 0.58)}">{emblem(p, w, w, w)}</g>
</svg>
'''


def inkscape() -> str:
    for cand in (os.environ.get("INKSCAPE"), "/Applications/Inkscape.app/Contents/MacOS/inkscape", shutil.which("inkscape")):
        if cand and Path(cand).exists():
            return cand
    sys.exit("Inkscape not found: install it or set INKSCAPE=/path/to/inkscape")


def render(svg: str, out: Path, size: int, tmp: Path) -> None:
    src = tmp / (out.stem + ".svg")
    src.write_text(svg)
    subprocess.run([inkscape(), str(src), "--export-type=png", f"--export-filename={out}",
                    f"--export-width={size}", f"--export-height={size}"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    Image.open(out).save(out, optimize=True)  # Inkscape writes unoptimised PNGs


def main() -> None:
    p = parts()
    img = WWW / "img"
    img.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    def write(name: str, text: str) -> None:
        path = img / name
        path.write_text(text)
        written.append(path)

    write("mark.svg", mark_symbols(p))
    write("icon.svg", tile(p))
    write("favicon.svg", tile(p, size=64, radius=0.2, height_frac=0.84, small=True, glow=False))
    write("logo.svg", lockup(p, adaptive=True))

    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        jobs = [
            ("icon-192.png", tile(p), 192),
            ("icon-512.png", tile(p), 512),
            ("icon-maskable-192.png", full_bleed(p, 512, 0.56), 192),
            ("icon-maskable-512.png", full_bleed(p, 512, 0.56), 512),
            ("apple-touch-icon.png", full_bleed(p, 512, 0.66), 180),
            ("icon-monochrome.png", monochrome(p), 512),
        ]
        for name, svg, size in jobs:
            render(svg, img / name, size, tmp)
            written.append(img / name)

        logo_png = img / "logo.png"
        src = tmp / "logo.svg"
        src.write_text(lockup(p, adaptive=False))
        subprocess.run([inkscape(), str(src), "--export-type=png", f"--export-filename={logo_png}", "--export-width=1024"],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        Image.open(logo_png).save(logo_png, optimize=True)
        written.append(logo_png)

        # favicon.ico: each size rendered on its own (not downscaled from 48) so 16 px stays crisp.
        small_svg = tile(p, size=64, radius=0.2, height_frac=0.84, small=True, glow=False)
        frames = []
        for s in (16, 32, 48):
            out = tmp / f"fav-{s}.png"
            render(small_svg, out, s, tmp)
            frames.append(Image.open(out).convert("RGBA"))
        ico = WWW / "favicon.ico"
        frames[-1].save(ico, format="ICO", sizes=[(16, 16), (32, 32), (48, 48)], append_images=frames[:-1])
        written.append(ico)

    for path in written:
        print(f"{path.stat().st_size:>8,}  {path.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
